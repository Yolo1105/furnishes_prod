function formatCents(cents: number | null, currency: string): string {
  if (cents == null) return "—";
  const code = currency.trim().toUpperCase() || "SGD";
  if (code === "SGD") {
    return `S$${Math.round(cents / 100).toLocaleString("en-SG")}`;
  }
  try {
    return new Intl.NumberFormat("en-SG", {
      style: "currency",
      currency: code,
      maximumFractionDigits: 0,
    }).format(cents / 100);
  } catch {
    return `${code} ${(cents / 100).toFixed(0)}`;
  }
}

function RoomPlanSection({ onAsk }: { onAsk: (prompt: string) => void }) {
  const [plans, setPlans] = useState<RoomPlanApi[]>([]);
  const [error, setError] = useState<string | null>(null);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    let cancelled = false;
    void (async () => {
      setLoading(true);
      setError(null);
      try {
        const response = await fetch("/api/account/room-plans");
        if (response.status === 503) {
          if (!cancelled) {
            setPlans([]);
            setError("Room plans are turned off.");
          }
          return;
        }
        if (!response.ok) {
          throw new Error("Failed to load room plans.");
        }
        const payload = (await response.json()) as { plans?: RoomPlanApi[] };
        if (!cancelled) setPlans(payload.plans ?? []);
      } catch {
        if (!cancelled) setError("Could not load room plans.");
      } finally {
        if (!cancelled) setLoading(false);
      }
    })();
    return () => {
      cancelled = true;
    };
  }, []);

  if (loading) {
    return <p className="wf-scard__d">Loading room plan…</p>;
  }
  if (error) {
    return <p className="wf-scard__d">{error}</p>;
  }
  if (!plans.length) {
    return (
      <p className="wf-scard__d">
        No room plan yet. Ask Eva to start one, or save recommendations into a
        plan when the feature flag is on.
      </p>
    );
  }

  const plan = plans[0]!;
  const cap = plan.budgetCapCents ?? 0;
  const remaining = plan.remainingBudgetCents ?? 0;
  const spent = Math.max(0, cap - remaining);
  const fillPct = cap > 0 ? Math.min(100, Math.round((spent / cap) * 100)) : 0;

  return (
    <>
      <div className="wf-srow">
        <span className="wf-srow__b">
          <span className="wf-srow__t">{plan.name}</span>
          <span className="wf-srow__m">
            {plan.readiness.label} · score {plan.readiness.score}
            {plan.readiness.overBudget ? " · over budget" : ""}
          </span>
        </span>
        <span
          className="wf-rthumb"
          aria-label={`Readiness ${plan.readiness.score}`}
          style={{
            display: "grid",
            placeItems: "center",
            fontSize: 12,
            fontWeight: 600,
          }}
        >
          {plan.readiness.score}
        </span>
      </div>

      <p className="wf-sec__lbl">Budget</p>
      <div className="wf-bdl">
        <div className="wf-bdrow">
          <span>Cap</span>
          <b>{formatCents(plan.budgetCapCents, plan.currency)}</b>
        </div>
        <div className="wf-bdrow">
          <span>Remaining</span>
          <b>{formatCents(plan.remainingBudgetCents, plan.currency)}</b>
        </div>
        <div
          className="wf-bdrow"
          style={{
            height: 8,
            padding: 0,
            marginTop: 8,
            background: "color-mix(in srgb, currentColor 12%, transparent)",
            borderRadius: 999,
            overflow: "hidden",
          }}
        >
          <div
            style={{
              width: `${fillPct}%`,
              height: "100%",
              background: "currentColor",
              opacity: 0.55,
            }}
          />
        </div>
      </div>

      <p className="wf-sec__lbl">Items</p>
      {plan.items.map((item) => (
        <div className="wf-srow" key={item.id}>
          <span className="wf-srow__b">
            <span className="wf-srow__t">
              {item.label}
              <span className="wf-srow__m" style={{ marginLeft: 8 }}>
                {item.priority} · {item.status}
              </span>
            </span>
            <span className="wf-srow__m">
              {formatCents(item.budgetCents, plan.currency)}
            </span>
          </span>
          <Action
            onClick={() =>
              onAsk(
                `Help me decide on the ${item.label} for my room plan. Remaining budget is ${formatCents(plan.remainingBudgetCents, plan.currency)}.`,
              )
            }
          >
            Ask Eva
          </Action>
        </div>
      ))}

      {plan.readiness.missingCore.length ? (
        <>
          <p className="wf-sec__lbl">Missing core</p>
          {plan.readiness.missingCore.map((label) => (
            <div className="wf-srow" key={label}>
              <span className="wf-srow__b">
                <span className="wf-srow__t">{label}</span>
                <span className="wf-srow__m">
                  still needed before ready to order
                </span>
              </span>
            </div>
          ))}
        </>
      ) : null}

      {plan.readiness.label === "ready to order" ? (
        <p className="wf-scard__d">
          {plan.orderCtaEnabled
            ? "Ready to order — checkout coming soon"
            : "Ready to order — checkout coming soon"}
        </p>
      ) : null}
    </>
  );
}
