function pressKey(
  event: React.KeyboardEvent<HTMLElement>,
  onClick: () => void,
) {
  if (event.key === "Enter" || event.key === " ") {
    event.preventDefault();
    onClick();
  }
}

/** Prototype uses span/div for chrome (not <button>) so Windows UA can’t paint cool grey-blue fills. */
function Action({
  children,
  onClick,
  dataAttr,
}: {
  children: React.ReactNode;
  onClick: () => void;
  dataAttr?: Record<string, string>;
}) {
  return (
    <span
      role="button"
      tabIndex={0}
      className="wf-exbtn"
      onClick={onClick}
      onKeyDown={(event) => pressKey(event, onClick)}
      {...dataAttr}
    >
      {children}
    </span>
  );
}

