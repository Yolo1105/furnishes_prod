export function ChatSectionView(props: ChatSectionViewProps) {
  const copy = SECTION_COPY[props.section];
  const [tasks, setTasks] = useState<Record<number, boolean>>({});
  const [shortlist, setShortlist] = useState<Record<string, boolean>>({});
  const [fileCategory, setFileCategory] = useState("All");
  const [selectedFile, setSelectedFile] = useState<string | null>(null);
  const previousSection = useRef(props.section);

  useEffect(() => {
    if (props.section === "files" && previousSection.current !== "files") {
      setFileCategory("All");
      setSelectedFile(null);
    }
    previousSection.current = props.section;
  }, [props.section]);

  useEffect(() => {
    if (props.section !== "files" || !selectedFile) return;
    function onKey(event: KeyboardEvent) {
      if (event.key !== "Escape") return;
      event.stopPropagation();
      setSelectedFile(null);
    }
    window.addEventListener("keydown", onKey, true);
    return () => window.removeEventListener("keydown", onKey, true);
  }, [props.section, selectedFile]);

  function ask(prompt: string) {
    props.onExit();
    props.onAsk(prompt);
  }

  function toggleShortlist(name: string) {
    setShortlist((current) => {
      const added = !current[name];
      props.onToast(
        added ? "Saved to your shortlist" : "Removed from shortlist",
      );
      return { ...current, [name]: added };
    });
  }

  return (
    <div className="wf-secv wf-viewin">
      <h1 className="wf-secv__h">{copy.title}</h1>
      <p className="wf-secv__sub">{copy.sub}</p>
      {props.section === "project" ? (
        <ProjectSection
          {...props}
          tasks={tasks}
          shortlist={shortlist}
          onToggleTask={(index) =>
            setTasks((current) => ({ ...current, [index]: !current[index] }))
          }
          onToggleShortlist={toggleShortlist}
        />
      ) : null}
      {props.section === "files" ? (
        <FilesSection
          selectedFile={selectedFile}
          category={fileCategory}
          onSelectFile={setSelectedFile}
          onSelectCategory={setFileCategory}
          onAsk={ask}
          onToast={props.onToast}
        />
      ) : null}
      {props.section === "discover" ? (
        <DiscoverSection
          preferences={props.confirmedPreferences}
          shortlist={shortlist}
          onToggleShortlist={toggleShortlist}
          onAsk={ask}
        />
      ) : null}
      {props.section === "plan" ? <RoomPlanSection onAsk={ask} /> : null}
    </div>
  );
}

